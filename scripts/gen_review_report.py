#!/usr/bin/env python3
"""Writes docs/CONTENT_REVIEW_REPORT.md from /content and scripts/review_notes.py."""
import json, pathlib, sys
sys.path.insert(0, str(pathlib.Path(__file__).parent))
from review_notes import NOTES, VENUE_NOTES

root = pathlib.Path(__file__).resolve().parent.parent
load = lambda p: json.loads((root / "content" / p).read_text())
topics = ["art", "music", "history", "politics", "geopolitics", "books", "philosophy"]
cards = [c for t in topics for c in load(f"cards/{t}.json")]
vocab = load("vocab/vocab.json")
events = load("events/events.json")
venues = load("events/venues.json")
unknown = set(NOTES) - {c["id"] for c in cards} - {v["id"] for v in vocab}
if unknown: sys.exit(f"notes for unknown ids: {unknown}")

pub = lambda items, key=lambda i: i["editorial"]["status"]: sum(1 for i in items if key(i) == "published")
L = []
L.append("# Content needing expert review\n")
L.append("Generated by `python3 scripts/gen_review_report.py`. Regenerate after each editorial pass.\n")
L.append("## Summary\n")
L.append("| | Seeded | Published | Spec target (Phase 1) |\n|---|---|---|---|")
for t in topics:
    items = [c for c in cards if c["topic"] == t]
    L.append(f"| Cards — {t} | {len(items)} | {pub(items)} | 30 |")
L.append(f"| Vocabulary entries | {len(vocab)} | {pub(vocab)} | 200 |")
L.append(f"| Events | {len(events)} (all samples) | {sum(1 for e in events if e['editorialStatus']=='published')} | verified listings for 3 cities |")
L.append("")
L.append("**Nothing is published.** Every item was drafted without human review and is in the `in_review` state. Debug and Beta builds show it with an \"En relecture\" banner; App Store builds show none of it.\n")
L.append("## What every item needs\n")
L.append("- **Cards:** a subject-matter expert checks facts, dates and the bilingual wording; confirms each source URL resolves and supports the claim; checks that the attached images and their captions suit the card; fills in `reviewer` and `lastReviewed` by publishing in the editor.")
L.append("- **Images:** all attached images are public-domain (CC0) works from the Art Institute of Chicago, chosen by hand and checked to load. Captions (alt text) were written for each one and need the same FR/EN review as the cards. Cards marked *missing* below have no honest match in open-access collections yet (e.g. the Berlin Wall, Hormuz, NATO); they show the topic artwork until an editor adds a licensed photo. Event images are illustrations, captioned as such, not pictures of the productions.")
L.append("- **Politics and geopolitics:** a check for neutrality and steel-manning of each position. Every geopolitics card carries a `factsAsOf` date that must be refreshed.")
L.append("- **Vocabulary:** a native-speaker reviewer (required by the editor) checks the definition, register label, example, nuances, pitfalls and etymology against TLFi and the Académie dictionary. English glosses need a native English check.")
L.append("- **Events:** all 15 are `[Exemple]` placeholders using real venue names and addresses. Replace them with listings from agreed sources (see `admin/sources.json`). They cannot be published.")
L.append("- **Source URLs:** most point to an institution's home page rather than the exact page. Deep-link each source during review.\n")
L.append("## Specific points to check\n")
for item in cards + vocab:
    if item["id"] in NOTES:
        title = item.get("title", {}).get("fr") or item.get("term")
        L.append(f"- **{item['id']}** ({title}): {NOTES[item['id']]}")
for v in venues:
    if v["id"] in VENUE_NOTES:
        L.append(f"- **Venue {v['name']}**: {VENUE_NOTES[v['id']]}")
L.append("")
L.append("## Full list\n")
L.append("| ID | Topic | Title / term | Sources | Images | Specific note |\n|---|---|---|---|---|---|")
for c in cards:
    L.append(f"| {c['id']} | {c['topic']} | {c['title']['fr']} | {len(c['editorial']['sources'])} | {(str(1 + len(c.get('gallery', []))) if c.get('image') else 'missing')} | {'see above' if c['id'] in NOTES else ''} |")
for v in vocab:
    L.append(f"| {v['id']} | vocabulaire ({v['register']}) | {v['term']} | {len(v['editorial']['sources'])} | n/a | {'see above' if v['id'] in NOTES else ''} |")
(root / "docs/CONTENT_REVIEW_REPORT.md").write_text("\n".join(L) + "\n")
print("wrote docs/CONTENT_REVIEW_REPORT.md")
